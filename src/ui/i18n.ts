/** Both tables, for the test that checks they have the same keys. */
export const UI_STRINGS: Record<UiLanguage, UiStrings> = { en, es };

let forced: UiLanguage | null = null;

/** Forces a language (tests); `null` goes back to following Obsidian. */
export function setUiLanguage(language: UiLanguage | null): void {
  forced = language;
}

/** `es`, `es-ES`, `es-419`… are Spanish; anything else, or nothing, is English. */
export function languageOf(locale: string | null | undefined): UiLanguage {
  return typeof locale === "string" && /^es(?:$|[-_])/i.test(locale) ? "es" : "en";
}

/** The interface language: Obsidian's when it is Spanish, else English. */
export function uiLanguage(): UiLanguage {
  if (forced) return forced;
  try {
    return languageOf(moment.locale());
  } catch {
    return "en";
  }
}

/** The interface strings in the current language. */
export function t(): UiStrings {
  return UI_STRINGS[uiLanguage()];
}

/** Name of a folder setting, as the settings tab shows it. */
export function folderSettingName(key: "jdexFolder" | "systemRoot" | "reportsFolder" | "templatesFolder"): string {
  const s = t();
  return { jdexFolder: s.setJdexFolder, systemRoot: s.setSystemRoot, reportsFolder: s.setReportsFolder, templatesFolder: s.setTemplatesFolder }[key];
}
